export type LangCode = (typeof LANGS)[number]['code']

const LANG_KEY = 'lang'

function detect(): LangCode {
  try {
    const saved = localStorage.getItem(LANG_KEY)
    if (saved && LANGS.some((l) => l.code === saved)) return saved as LangCode
  } catch {
    /* ignore */
  }
  for (const tag of navigator.languages ?? [navigator.language]) {
    const base = tag.toLowerCase().split('-')[0]
    const hit = LANGS.find((l) => l.code === base)
    if (hit) return hit.code
  }
  return 'en'
}

let current: LangCode = detect()

export const getLang = () => current
export const isRtl = () => LANGS.some((l) => l.code === current && 'rtl' in l && l.rtl)

export function setLang(code: LangCode) {
  current = code
  try {
    localStorage.setItem(LANG_KEY, code)
  } catch {
    /* ignore */
  }
}

export function t(key: Key): string {
  const lang = LANGS.find((l) => l.code === current)
  return lang?.dict[key] ?? en[key]
}

// Образные названия цветов есть на русском и английском; остальные языки пока показывают английские.
export function colorName(c: NamedColor): string {
  return current === 'ru' ? c.ru : c.en
}

// Строка с подстановками: tf('copied', { hex: '#AABBCC' })
export function tf(key: Key, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}
